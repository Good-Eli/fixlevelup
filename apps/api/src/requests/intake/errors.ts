import { HttpException } from '@nestjs/common';

export type RequestFailureCode = 'INVALID_REQUEST' | 'UNPROCESSABLE' | 'NOT_FOUND' | 'NOT_READY' | 'FORBIDDEN'
  | 'CONFLICT' | 'CITY_CONTEXT_STALE' | 'CONSENT_REQUIRED' | 'FORM_ALREADY_SUBMITTED' | 'IDEMPOTENCY_KEY_REUSED'
  | 'REQUEST_RULES_UNAVAILABLE' | 'CHANNEL_OPTIONS_CHANGED' | 'CHANNEL_OFFER_DISABLED' | 'CHANNEL_NOT_READY'
  | 'PRECONDITION_REQUIRED' | 'PRECONDITION_FAILED' | 'COVERAGE_ASSESSMENT_STALE' | 'DEPENDENCY_UNAVAILABLE'
  | 'BODY_TOO_LARGE' | 'QUOTA';

const STATUS: Record<RequestFailureCode, number> = {
  INVALID_REQUEST: 400, UNPROCESSABLE: 422, NOT_FOUND: 404, NOT_READY: 503, FORBIDDEN: 403,
  CONFLICT: 409, CITY_CONTEXT_STALE: 409, CONSENT_REQUIRED: 409, FORM_ALREADY_SUBMITTED: 409,
  IDEMPOTENCY_KEY_REUSED: 409, REQUEST_RULES_UNAVAILABLE: 503, CHANNEL_OPTIONS_CHANGED: 409,
  CHANNEL_OFFER_DISABLED: 409, CHANNEL_NOT_READY: 409, PRECONDITION_REQUIRED: 428, PRECONDITION_FAILED: 412,
  COVERAGE_ASSESSMENT_STALE: 409, DEPENDENCY_UNAVAILABLE: 503, BODY_TOO_LARGE: 413, QUOTA: 429,
};

export class RequestFailure extends HttpException {
  constructor(readonly code: RequestFailureCode) { super(code, STATUS[code]); this.name = 'RequestFailure'; }
}

export function deny(code: RequestFailureCode): never { throw new RequestFailure(code); }
