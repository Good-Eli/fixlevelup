import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { P05_OPENAPI } from './p05-openapi.mjs';

const banner = '// Generated by generate-p05.mjs from p05-openapi.mjs. Do not edit.\n';
const p05Dist = new URL('./dist/', import.meta.url);

/**
 * The P05 artifact is data-only: the DTO types and decoders are hand-written in
 * `src/p05.ts` (they carry the closed/duplicate-aware behaviour), so unlike P04
 * nothing is code-generated. This module only freezes the OpenAPI document.
 */
export function renderP05() {
  return { 'p05-openapi.json': `${JSON.stringify(P05_OPENAPI, null, 2)}\n` };
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  mkdirSync(fileURLToPath(p05Dist), { recursive: true });
  for (const [filename, content] of Object.entries(renderP05())) {
    writeFileSync(new URL(filename, p05Dist), content);
  }
  console.log('P05 OpenAPI artifact written: dist/p05-openapi.json');
}

export { banner, p05Dist };
