import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { P04BodyLimit, P04_OPENAPI, P04_PREFIX } from './p04-openapi.mjs';

const pretty = (value) => JSON.stringify(value, null, 2);
const banner = '// Generated by generate-p04.mjs from p04-openapi.mjs. Do not edit.\n';
const componentName = (reference) => reference.slice('#/components/schemas/'.length);
const schemaName = (operation, suffix) => operation[0].toUpperCase() + operation.slice(1) + suffix;
const { schemas } = P04_OPENAPI.components;
const operationEntries = Object.entries(P04_OPENAPI.paths).flatMap(([path, methods]) => Object.entries(methods).map(([method, op]) => {
  const parameters = op.parameters.filter(x => x.in === 'path');
  const query = Object.fromEntries(op.parameters.filter(x => x.in === 'query').map(({ name, schema }) => [name, schema]));
  const metadata = { method: method.toUpperCase(), path, ...op['x-p04'], params: parameters.map(x => x.name), query: Object.keys(query) };
  return [op.operationId, {
    metadata, query, parameters: Object.fromEntries(parameters.map(({name, schema}) => [name, schema])),
    body: op.requestBody?.content['application/json'].schema,
    data: op.responses[op['x-p04'].status].content['application/json'].schema.properties.data,
  }];
}));
const literal = (v) => JSON.stringify(v);
const objectType = (fields, required, empty = 'Readonly<Record<string, never>>') => {
  const keys = Object.keys(fields);
  return keys.length ? `{ ${keys.map(key => `readonly ${literal(key)}${required.includes(key) ? '' : '?'}: ${schemaType(fields[key])};`).join(' ')} }` : empty;
};
function schemaType(schema) {
  if (schema.$ref) { return componentName(schema.$ref); }
  if (schema.oneOf) { return schema.oneOf.map(schemaType).join(' | '); }
  if (schema.enum) { return schema.enum.map(literal).join(' | '); }
  switch (schema.type) {
    case 'integer': return 'number';
    case 'string':
    case 'boolean':
    case 'null': return schema.type;
    case 'array': return `readonly (${schemaType(schema.items)})[]`;
    case 'object': return schema.additionalProperties === false
      ? objectType(schema.properties, schema.required)
      : `Readonly<Record<string, ${schemaType(schema.additionalProperties)}>>`;
    default: throw new TypeError('Unsupported P04 schema type');
  }
}
const routeRef = new Map(operationEntries);
if (routeRef.size !== operationEntries.length) { throw new TypeError('Duplicate P04 operationId'); }

// Keep the generated module platform-neutral: no Node APIs, networking, retries or browser credentials.
function runtime(P04_PREFIX, P04_ROUTES, schemas, operationShapes, csrfSchema) {
  const invalid = () => { throw new TypeError('Invalid P04 value'); };
  const ownValue = (object, key) => {
    const desc = Object.getOwnPropertyDescriptor(object, key);
    return desc?.enumerable && Object.hasOwn(desc, 'value') ? desc : null;
  };
  const plain = (value) => value !== null && typeof value === 'object' &&
    (Object.getPrototypeOf(value) === Object.prototype || Object.getPrototypeOf(value) === null);
  const regexp = new Map();
  const test = (pattern, value) => {
    if (!regexp.has(pattern)) { regexp.set(pattern, new RegExp(pattern, 'u')); }
    return regexp.get(pattern).test(value);
  };
  const exactDate = (value) => {
    const time = Date.parse(value);
    return Number.isFinite(time) && new Date(time).toISOString() === value;
  };
  const distinct = (values) => new Set(values).size === values.length;
  const missing = (value) => value === null || value === undefined;
  const ordered = (min, max) => missing(min) || missing(max) || BigInt(min) <= BigInt(max);
  function refine(rule, value) {
    if (rule === undefined) { return true; }
    if (rule === 'instant') { return exactDate(value); }
    if (rule === 'date') { return exactDate(`${value}T00:00:00.000Z`); }
    if (rule === 'nonblank') { return value.trim().length > 0; }
    const [kind, start] = rule.split('-');
    if (!missing(value.validUntil) && value.validUntil <= value[start]) { return false; }
    if (kind === 'schedule') { return true; }
    if (kind === 'estimate') { return ordered(value.minMinor, value.maxMinor); }
    if (kind === 'rule') {
      return (missing(value.startMinute) || (value.startMinute !== value.endMinute && value.wrapsMidnight === (value.startMinute > value.endMinute)))
        && ordered(value.minBase, value.maxBase) && ordered(value.minDelta, value.maxDelta);
    }
    if (kind === 'policy') {
      const pairs = value.compatibilities.map(({ leftRuleId: left, rightRuleId: right }) => left === right ? null : [left, right].sort().join(':'));
      return !pairs.includes(null) && distinct(pairs) && distinct(value.priorities.map(({ ruleId }) => ruleId));
    }
    return false;
  }
  function accepts(schema, value) {
    if (schema.$ref) { return accepts(schemas[schema.$ref.slice('#/components/schemas/'.length)], value); }
    if (schema.oneOf) { return schema.oneOf.filter(part => accepts(part, value)).length === 1; }
    if (schema.enum && !schema.enum.includes(value)) { return false; }
    if (schema.type === 'null') { return value === null; }
    if (schema.type === 'boolean') { return typeof value === 'boolean'; }
    if (schema.type === 'integer') { return Number.isSafeInteger(value) && !Object.is(value, -0) && value >= schema.minimum && value <= schema.maximum; }
    if (schema.type === 'string') {
      if (typeof value !== 'string' || value.length > (schema.maxLength ?? Infinity) * 2) { return false; }
      const length = Array.from(value).length;
      return length >= (schema.minLength ?? 0) && length <= (schema.maxLength ?? Infinity)
        && (!schema.pattern || test(schema.pattern, value)) && refine(schema['x-p04-refine'], value);
    }
    if (schema.type === 'array') {
      if (!Array.isArray(value) || Object.getPrototypeOf(value) !== Array.prototype || value.length > schema.maxItems || Reflect.ownKeys(value).length !== value.length + 1) { return false; }
      const values = [];
      for (let i = 0; i < value.length; i++) {
        const desc = ownValue(value, String(i));
        if (!desc || !accepts(schema.items, desc.value)) { return false; }
        values.push(desc.value);
      }
      return !schema.uniqueItems || distinct(values);
    }
    if (schema.type === 'object') {
      if (!plain(value)) { return false; }
      const keys = Reflect.ownKeys(value);
      const props = schema.properties ?? {};
      if (keys.length < (schema.minProperties ?? 0) || keys.length > (schema.maxProperties ?? Object.keys(props).length)
          || schema.required?.some(key => !Object.hasOwn(value, key))) { return false; }
      const own = Object.create(null);
      for (const key of keys) {
        if (typeof key !== 'string' || (schema.propertyNames && !accepts(schema.propertyNames, key))) { return false; }
        const field = Object.hasOwn(props, key) ? props[key] : schema.additionalProperties;
        const desc = ownValue(value, key);
        if (!field || !desc || !accepts(field, desc.value)) { return false; }
        own[key] = desc.value;
      }
      return refine(schema['x-p04-refine'], own);
    }
    return false;
  }
  const assert = (schema, value) => accepts(schema, value) ? value : invalid();
  const known = (operation) => Object.hasOwn(operationShapes, operation) ? operationShapes[operation] : invalid();
  const closed = (properties, required = []) => ({ type: 'object', properties, additionalProperties: false, required });
  const decodeP04Body = (operation, value) => {
    const schema = known(operation).body;
    return schema ? assert(schema, value) : invalid();
  };
  const decodeP04Data = (operation, value) => assert(known(operation).data, value);
  const decodeP04Query = (operation, value) => assert(closed(known(operation).query), value);
  const decodeP04Params = (operation, value) => assert(closed(known(operation).parameters, P04_ROUTES[operation].params), value);
  const routeLookup = new Map();
  for (const [operation, route] of Object.entries(P04_ROUTES)) {
    const parts = route.path.split('/');
    const shape = route.method + ':' + parts.length;
    const rows = routeLookup.get(shape) ?? [];
    rows.push({ operation, parts });
    routeLookup.set(shape, rows);
  }
  function matchP04Route(method, rawPath) {
    if ((method !== 'GET' && method !== 'POST') || typeof rawPath !== 'string' || rawPath.length > 256 || !rawPath.startsWith(P04_PREFIX + '/')) { return null; }
    const parts = rawPath.split('/');
    const candidates = routeLookup.get(method + ':' + parts.length) ?? [];
    for (const { operation, parts: template } of candidates) {
      const params = {};
      const ok = template.every((part, index) => {
        const actual = parts[index];
        if (!part.startsWith('{')) { return part === actual; }
        const key = part.slice(1, -1);
        if (!accepts(operationShapes[operation].parameters[key], actual)) { return false; }
        params[key] = actual;
        return true;
      });
      if (ok) { return { operation, params }; }
    }
    return null;
  }
  function createP04Client(transport) {
    if (typeof transport !== 'function') { return invalid(); }
    return Object.freeze({ async request(operation, input = {}) {
      known(operation);
      if (!plain(input)) { return invalid(); }
      const route = P04_ROUTES[operation];
      const mutation = route.method === 'POST';
      const keys = ['params', 'query', ...mutation ? ['body', 'idempotencyKey', 'csrfToken', ...route.versioned ? ['expectedVersion'] : []] : []];
      if (Reflect.ownKeys(input).some(key => !keys.includes(key) || !ownValue(input, key))) { return invalid(); }
      const params = decodeP04Params(operation, Object.hasOwn(input, 'params') ? input.params : {});
      const query = decodeP04Query(operation, Object.hasOwn(input, 'query') ? input.query : {});
      const queryString = Object.keys(query).sort().map(key => key + '=' + encodeURIComponent(query[key])).join('&');
      const pathname = route.path.replace(/\{([a-zA-Z]+)\}/gu, (_, key) => params[key]);
      const path = queryString ? pathname + '?' + queryString : pathname;
      const headers = { Accept: 'application/json, application/problem+json' };
      let body;
      if (mutation) {
        const headerSchemas = operationShapes[operation].headers;
        body = JSON.stringify(decodeP04Body(operation, Object.hasOwn(input, 'body') ? input.body : undefined));
        if (new TextEncoder().encode(body).length > route.bodyLimit) { return invalid(); }
        headers['Content-Type'] = 'application/json; charset=utf-8';
        headers['Idempotency-Key'] = assert(headerSchemas['Idempotency-Key'], Object.hasOwn(input, 'idempotencyKey') ? input.idempotencyKey : undefined);
        headers['X-CSRF-Token'] = assert(csrfSchema, Object.hasOwn(input, 'csrfToken') ? input.csrfToken : undefined);
        if (route.versioned) {
          const expectedVersion = Object.hasOwn(input, 'expectedVersion') && input.expectedVersion;
          if (!Number.isSafeInteger(expectedVersion) || expectedVersion < (route.allowZero ? 0 : 1) || Object.is(expectedVersion, -0)) { return invalid(); }
          headers['If-Match'] = assert(headerSchemas['If-Match'], `"p04-v${expectedVersion}"`);
        }
      }
      const reply = await transport({ operation, method: route.method, path, headers, ...(mutation ? { body } : {}) });
      if (!reply || (reply.status !== route.status && !(mutation && reply.status === 200))) { throw new TypeError('Unexpected P04 response status'); }
      const envelope = assert(operationShapes[operation].envelope, reply.body);
      return { ...envelope, status: reply.status };
    } });
  }
  return { matchP04Route, decodeP04Params, decodeP04Body, decodeP04Data, decodeP04Query, createP04Client };
}

export function renderP04() {
  const routes = Object.fromEntries(operationEntries.map(([id, { metadata }]) => [id, metadata]));
  const routeShapes = Object.fromEntries(operationEntries.map(([id, { metadata, body, ...shapes }]) => {
    const op = P04_OPENAPI.paths[metadata.path][metadata.method.toLowerCase()];
    return [id, { ...shapes, body, envelope: op.responses[metadata.status].content['application/json'].schema,
      headers: Object.fromEntries(op.parameters.filter(x => x.in === 'header').map(({name,schema}) => [name, schema])) }];
  }));
  const implementation = banner + `export const P04_PREFIX = ${literal(P04_PREFIX)};\n`
    + `export const P04BodyLimit = Object.freeze(${pretty(P04BodyLimit)});\n`
    + `const schemas = ${pretty(schemas)};\nconst operationShapes = ${pretty(routeShapes)};\n`
    + `const csrfSchema = ${pretty(P04_OPENAPI.components.securitySchemes.sessionCsrf['x-p04-schema'])};\n`
    + `export const P04_ROUTES = ${pretty(routes)};\n`
    + `for (const route of Object.values(P04_ROUTES)) {\n  for (const field of ['permissions', 'params', 'query']) { Object.freeze(route[field]); }\n  Object.freeze(route);\n}\nObject.freeze(P04_ROUTES);\n`
    + `export const { matchP04Route, decodeP04Params, decodeP04Body, decodeP04Data, decodeP04Query, createP04Client } = (${runtime.toString()})(P04_PREFIX, P04_ROUTES, schemas, operationShapes, csrfSchema);\n`;
  const permissions = [...new Set(Object.values(routes).flatMap(route => route.permissions))];
  const pathsDeclaration = operationEntries.map(([id, {metadata, query, parameters}]) => {
    const entries = Object.entries(metadata).map(([key, value]) => {
      const valueType = key === 'permissions' ? 'readonly P04Permission[]'
        : Array.isArray(value) ? `readonly [${value.map(literal).join(', ')}]` : literal(value);
      return `readonly ${key}: ${valueType};`;
    }).join(' ');
    const params = Object.keys(parameters);
    return { id, metadata, entries, queryType: objectType(query, []), paramsType: objectType(parameters, params), params };
  });
  const typeTable = (label, make) => `interface ${label} {\n${pathsDeclaration.map(op => `  readonly ${op.id}: ${make(op)};`).join('\n')}\n}\n`;
  const types = banner + `export declare const P04_PREFIX: ${literal(P04_PREFIX)};\n`
    + `export declare const P04BodyLimit: { ${Object.entries(P04BodyLimit).map(([key, value]) => `readonly ${key}: ${value};`).join(' ')} };\n`
    + `export type P04BodyLimit = typeof P04BodyLimit[keyof typeof P04BodyLimit];\n`
    + `export type P04Permission = ${permissions.map(literal).join(' | ')};\n`
    + Object.entries(schemas).map(([name, schema]) => `${['Receipt','RevisionReceipt','Problem'].includes(name) ? 'export ' : ''}type ${name} = ${schemaType(schema)};`).join('\n') + '\n'
    + typeTable('Routes', op => `{ ${op.entries} }`)
    + typeTable('Params', op => op.paramsType)
    + typeTable('Queries', op => op.queryType)
    + typeTable('Bodies', op => op.metadata.method === 'POST' ? schemaName(op.id, 'Body') : 'never')
    + typeTable('Data', op => schemaName(op.id, 'Data'))
    + `export declare const P04_ROUTES: Routes;
export type P04Operation = keyof Routes;
export type P04MutationOperation = { [K in P04Operation]: Routes[K]['method'] extends 'POST' ? K : never }[P04Operation];
export type P04Params<Op extends P04Operation> = Params[Op];
export type P04Query<Op extends P04Operation> = Queries[Op];
export type P04Body<Op extends P04Operation> = Bodies[Op];
export type P04Data<Op extends P04Operation> = Data[Op];
export type P04Match = { [K in P04Operation]: { readonly operation: K; readonly params: Params[K] & Readonly<Record<string, string>> } }[P04Operation];
export declare function matchP04Route(method: string, rawPath: string): P04Match | null;
export declare function decodeP04Params<Op extends P04Operation>(operation: Op, value: unknown): P04Params<Op>;
export declare function decodeP04Body<Op extends P04MutationOperation>(operation: Op, value: unknown): P04Body<Op>;
export declare function decodeP04Data<Op extends P04Operation>(operation: Op, value: unknown): P04Data<Op>;
export declare function decodeP04Query<Op extends P04Operation>(operation: Op, value: unknown): P04Query<Op>;
export interface P04TransportRequest {
  readonly operation: P04Operation;
  readonly method: 'GET' | 'POST';
  readonly path: string;
  readonly headers: Readonly<Record<string, string>>;
  readonly body?: string;
}
export type P04Transport = (request: P04TransportRequest) => Promise<{ readonly status: number; readonly body: unknown }>;
export type P04Request<Op extends P04Operation> = (Routes[Op]['params'] extends readonly [] ? { readonly params?: Params[Op] } : { readonly params: Params[Op] })
  & { readonly query?: Queries[Op] }
  & (Op extends P04MutationOperation
    ? { readonly body: Bodies[Op]; readonly idempotencyKey: string; readonly csrfToken: string }
      & (Routes[Op]['versioned'] extends true ? { readonly expectedVersion: number } : { readonly expectedVersion?: never })
    : { readonly body?: never; readonly idempotencyKey?: never; readonly csrfToken?: never; readonly expectedVersion?: never });
export type P04Result<Op extends P04Operation> = {
  readonly data: Data[Op]; readonly meta: { readonly requestId: string }; readonly status: Routes[Op]['status'] | 200;
};
export interface P04Client {
  request<Op extends P04Operation>(operation: Op, input: P04Request<NoInfer<Op>>): Promise<P04Result<Op>>;
}
export declare function createP04Client(transport: P04Transport): P04Client;
`;
  return { 'p04.js': implementation, 'p04.d.ts': types, 'p04-openapi.json': pretty(P04_OPENAPI) + '\n' };
}
export const p04Dist = new URL('./dist/', import.meta.url);
if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  mkdirSync(fileURLToPath(p04Dist), { recursive: true });
  for (const [filename, content] of Object.entries(renderP04())) { writeFileSync(new URL(filename, p04Dist), content); }
}
